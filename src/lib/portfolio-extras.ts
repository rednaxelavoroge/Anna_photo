import type { TagStripExtra } from "@/components/TagStrip";
import type { StudioTag } from "@/lib/content";

/**
 * «Фототуры» в строке подразделов «Путешествий».
 *
 * История. До 05.09.2026 фототуры были отдельным пунктом главного меню;
 * заказчица попросила убрать пункт и держать их там же, где Армения и Италия.
 * Тогда это сделали простой ссылкой в той же строке: своих кадров у фототуров
 * не было, меткой сделать было нечего.
 *
 * 06.09.2026 заказчица попросила «такой же подраздел, как Италия и Армения» —
 * то есть чтобы по нажатию открывались кадры, а не страница с описанием.
 * Метка `fototur` заведена; дальше всё делается само:
 *
 * - **Пока ни один кадр меткой не отмечен** — метки в строке нет (строка
 *   показывает только те, что кому-то поставлены), и на её месте стоит
 *   ссылка на страницу с описанием, как было. Раздел не пустеет на то время,
 *   пока заказчица не разложила кадры.
 * - **Как только отмечен первый кадр** — встаёт настоящий подраздел с
 *   кадрами, а ссылка отсюда уходит: два одинаковых слова в строке не нужны.
 *   Страница с описанием никуда не девается, ссылка на неё показывается
 *   внутри самого подраздела и называется «О фототурах».
 */
export const PHOTOTOUR_CATEGORY = "travel";
export const PHOTOTOUR_TAG = "fototur";

type Where = {
  /** Метки, у которых в этом разделе есть кадры. */
  tags: StudioTag[];
  /** Открытый подраздел, если открыт. */
  album?: string;
  /** Открыта страница с описанием фототуров. */
  onPhototourPage?: boolean;
};

export function extrasFor(categorySlug: string, where: Where): TagStripExtra[] {
  if (categorySlug !== PHOTOTOUR_CATEGORY) return [];
  const живая = where.tags.some((tag) => tag.slug === PHOTOTOUR_TAG);

  // Кадров у подраздела ещё нет — держим ссылку на описание вместо метки.
  if (!живая) {
    return [{ href: "/phototour", name: "Фототуры", active: Boolean(where.onPhototourPage) }];
  }

  // Кадры есть. Ссылку на описание показываем только там, где она к месту:
  // внутри самого подраздела и на самой странице описания.
  if (where.album === PHOTOTOUR_TAG || where.onPhototourPage) {
    return [{ href: "/phototour", name: "О фототурах", active: Boolean(where.onPhototourPage) }];
  }

  return [];
}
